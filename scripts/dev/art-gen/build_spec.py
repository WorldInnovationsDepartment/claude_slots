p("""## 6. Hot-state rule (indivisible)

**One rule, always applied together, never one without the other:** a matched/winning reel cell switches its box from the single-line set (`┌─┐│└┘`) to the double-line set (`╔═╗║╚╝`) **and** its glyph renders bold, at the same instant, as one atomic state change. A terminal with no bold support still reads "hot" correctly from the glyph swap alone; a terminal that can't render box-drawing doubles (rare) still reads "hot" from the bold weight. Never emit bold without the double-line swap, and never swap to double-line without also setting bold — a renderer that did either alone would be implementing half a rule.

This applies **per reel-cell-column** (all three symbols in a hot reel's box go double/bold together, not just the payline cell) and only ever to reel cells — the outer cabinet shell is always double-line `╔═╗║╚╝╠╣` regardless of state (it is the fixed chrome chassis); "hot" is expressed there only through the color table's hue shift (§9), never a glyph change. On a DOUBLE win only the matched two of three reel columns go hot; on TRIPLE/MEDALLION/JACKPOT, all three do.
""")


