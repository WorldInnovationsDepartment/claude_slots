p("""## 4. RNG algorithm (outcome-first, seeded, unit-testable)

**Do not spin three independent reels and hope the probabilities fall out right.** Pick the outcome class first, resolve the payline to match it, then derive the two dressing rows purely from §3's static neighbor table (no further randomness). This is the same architecture all three source designs converged on, and it is what makes the whole system trivially unit-testable: given a seed, the output is fixed forever.

```
function spin(seed):
    rng = mulberry32(seed)                 # any seeded PRNG returning floats in [0,1)

    outcomeClass = rollOutcomeClass(rng)   # step 1 — consumes exactly 1 rng() call
    payline      = resolvePayline(outcomeClass, rng)   # step 2 — consumes 0-3 rng() calls
    grid         = fillNonPaylineRows(payline)         # step 3 — PURE, no rng() calls
    frame        = render(grid, outcomeClass)          # step 4

    return frame

function rollOutcomeClass(rng):
    r = rng()
    table = [ (JACKPOT, .015), (MEDALLION, .025), (TRIPLE, .080),
              (DOUBLE, .260), (NEAR_MISS, .120), (LOSE, .500) ]
    acc = 0
    for (class, p) in table:
        acc += p
        if r < acc: return class
    return LOSE   # floating-point fallback, never reached if table sums to 1.0

function resolvePayline(class, rng):
    switch class:
      case JACKPOT:    return [CLAUDE, CLAUDE, CLAUDE]
      case MEDALLION:  return [MEDALLION, MEDALLION, MEDALLION]
      case TRIPLE:
          tier = weightedPick(rng, TRIPLE_TIERS)     # BAR .010 TEST .010 TOKEN .012
                                                      # FILE .015 DIFF .016 PROSE .017 (of .08)
          return [tier, tier, tier]
      case DOUBLE:
          tier   = weightedPick(rng, DOUBLE_TIERS)   # CLAUDE .010 BAR .010 TEST .020 TOKEN .030
                                                      # FILE .045 DIFF .065 PROSE .080 (of .26)
          oddPos = floor(rng() * 3)                  # which of the 3 reels is the odd one out
          filler = uniformPick(rng, ALL_SYMBOLS - {tier, MEDALLION})
          line = [tier, tier, tier]; line[oddPos] = filler
          return line
      case NEAR_MISS:
          # near-miss symbol choice is deliberately biased toward the rarer/flashier
          # symbols (the well-documented "near-miss effect") -- it does NOT reuse the
          # dressing weights from §1.
          sym = weightedPick(rng, NEARMISS_WEIGHTS)  # CLAUDE .30 MEDALLION .20 BAR .15 TEST .12
                                                      # TOKEN .10 FILE .06 DIFF .04 PROSE .03
          return [sym, sym, NEXT(sym)]               # reel 3 is always the "off" reel (see §5)
      case LOSE:
          loop:
              [a, b, c] = [uniformPick(rng, ALL_SYMBOLS) for _ in range(3)]
              if len(set([a,b,c])) == 3 and not looksLikeNearMiss(a,b,c):
                  return [a, b, c]                   # reroll on accidental match/near-miss shape

function fillNonPaylineRows(payline):               # NO randomness -- pure function of payline
    above = [ PREV(s) for s in payline ]             # row rendered above the payline
    below = [ NEXT(s) for s in payline ]             # row rendered below the payline
    return { above, payline, below }
```

**Unit-test shape:** because `fillNonPaylineRows` is pure and `resolvePayline`/`rollOutcomeClass` are the only calls that touch `rng`, a test can assert the full 3×3 grid for a fixed seed with zero mocking. Worked examples from a reference `mulberry32` implementation (included in `build_spec.py`), so implementers can cross-check their own PRNG port against these exact numbers:

```
seed=    257  class=JACKPOT     payline=[CLAUDE,CLAUDE,CLAUDE]  above=[PROSE,PROSE,PROSE]  below=[BAR,BAR,BAR]
seed=     45  class=MEDALLION   payline=[MEDALLION x3]          above=[PROSE,PROSE,PROSE]  below=[BAR,BAR,BAR]
seed=     25  class=TRIPLE      payline=[TOKEN,TOKEN,TOKEN]     above=[TEST,TEST,TEST]     below=[FILE,FILE,FILE]
seed=      7  class=NEAR_MISS   payline=[TEST,TEST,TOKEN]       above=[BAR,BAR,TEST]       below=[TOKEN,TOKEN,FILE]
seed=      1  class=DOUBLE      payline=[PROSE,FILE,PROSE]      above=[DIFF,TOKEN,DIFF]    below=[MEDALLION,DIFF,MEDALLION]
seed=      3  class=LOSE        payline=[TOKEN,TEST,BAR]        above=[TEST,BAR,CLAUDE]    below=[FILE,TOKEN,TEST]
```

Any conforming `mulberry32(seed)` port that reproduces these six rows for these six seeds has a correct implementation of §2's probability table and §3's neighbor table simultaneously.
""")

