p("""## 5. Near-miss rule & the overshoot beat

**The deterministic rule:** a NEAR MISS payline is always `[S, S, NEXT(S)]` — reels 1 and 2 land on the same symbol `S`, reel 3 (always reel 3, never 1 or 2) lands on `S`'s fixed forward neighbor from §3's static table. There is no fuzziness here: "one step off" means exactly one entry in one static lookup table, the same table that drives the dressing rows, so a near miss is never a coincidence of independent RNG rolls — it is deliberately constructed to be exactly one reel-strip position away from a real win.

**The overshoot beat** (grafted from design #0, extended with the deterministic rule above): during STOPPING, once reels 1 and 2 have locked on `S`, reel 3's final deceleration briefly **overshoots** — it shows `S` for one frame (completing an illusory `SSS`), then snaps one stop further along its strip to the true, settled `NEXT(S)`. This is a single extra ~80ms frame inserted between "reel 3 still blurred" and "reel 3 locked" — see §8.5 for the literal frames (`★ ★ ★` flashing for one frame, then settling to `★ ★ ☼`).
""")

