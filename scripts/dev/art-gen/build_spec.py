p("""## 3. Canonical reel strips & neighbor table

Three reels, three *different-length* circular strips (20–24 stops), built once, hard-coded, never regenerated at runtime. Each strip is a concatenation of laps around one master symbol cycle — `✻ → BAR → ★ → ☼ → ♣ → ♦ → ♥ → ◆C◆ → (loops)` — where common symbols get extra laps (to bias SPINNING-blur/dressing frequency per §1's weight column) while the four rare/special symbols (`✻`, `BAR`, `★`, `◆C◆`) appear with identical counts on every reel. This single construction rule is what makes reels differ in *length and common-symbol density* while sharing one universal, deterministic neighbor table.

```
Reel 1 (22 stops): ✻ BAR ★ ☼ ♣ ♦ ♥ ◆C◆ BAR ☼ ♣ ♦ ♥ ☼ ♣ ♦ ♥ ♣ ♦ ♥ ♥ ♥
Reel 2 (24 stops): ✻ BAR ★ ☼ ♣ ♦ ♥ ◆C◆ BAR ☼ ♣ ♦ ♥ ☼ ♣ ♦ ♥ ♣ ♦ ♥ ♣ ♦ ♥ ♥
Reel 3 (20 stops): ✻ BAR ★ ☼ ♣ ♦ ♥ ◆C◆ BAR ☼ ♣ ♦ ♥ ☼ ♣ ♦ ♥ ♦ ♥ ♥
```

Symbol counts per reel (sum = strip length): `✻`×1, `BAR`×2, `★`×1, `◆C◆`×1 on every reel; `☼`×3 on every reel; `♣`/`♦`/`♥` vary — Reel1 `♣`4 `♦`4 `♥`6, Reel2 `♣`5 `♦`5 `♥`6, Reel3 `♣`3 `♦`4 `♥`5.

**Neighbor rule:** for a given reel, each symbol's canonical neighbor is read off its *first occurrence* on that reel's strip: `NEXT(sym) = strip[(firstIndex(sym) + 1) mod length]`, `PREV(sym) = strip[(firstIndex(sym) − 1) mod length]`. Because the four rare symbols are laid out identically at the head of every reel's strip, this table comes out **identical across all three reels** — one static lookup table, no per-reel branching needed at runtime:

| Symbol | NEXT (row below payline / near-miss forward neighbor) | PREV (row above payline) |
|---|---|---|
| `✻` CLAUDE | `BAR` | `♥` PROSE |
| `BAR` TOOL | `★` TEST | `✻` CLAUDE |
| `★` TEST | `☼` TOKEN | `BAR` TOOL |
| `☼` TOKEN | `♣` FILE | `★` TEST |
| `♣` FILE | `♦` DIFF | `☼` TOKEN |
| `♦` DIFF | `♥` PROSE | `♣` FILE |
| `♥` PROSE | `◆C◆` MEDALLION | `♦` DIFF |
| `◆C◆` MEDALLION | `BAR` TOOL | `♥` PROSE |

This table is what makes the cabinet feel mechanically real even at rest: **row above a payline symbol is always its `PREV`, row below is always its `NEXT`** — e.g. a `✻✻✻` payline *always* shows `♥ ♥ ♥` above and `BAR BAR BAR` below, in every idle frame, every JACKPOT frame, forever (see the JACKPOT storyboard, §8.7 — this is not coincidence, it is §4 step 3 applied literally).
""")

