p("""## 11. 1 fps degradation notes (statusLine / Tier 2 target)

Core rule: **design for discrete states, not motion-blur continuity.** At 1fps you get one paint per second — every phase below is built so its single most important frame is guaranteed to land on at least one tick.

- **IDLE** — bulbs alternate once per tick rather than every 600ms; reads as a slow, calm blink, which suits attract-mode fine. ON THE HOUSE degrades trivially since it's just IDLE with different text.
- **LEVER PULL (§8.2)** — skip straight from "grip" (knob0) to "yank!" (knob4); drop the three mid-frames entirely. The credits-decremented number carries the meaning even without seeing the knob travel.
- **SPIN-UP (§8.3)** — collapses to a single "all reels now blurred" frame; the wind-up choreography is an 8-12fps-only flourish.
- **SPINNING (§8.4)** — render the steady-blur frame every tick, with the ticker as the only thing that must visibly change every tick. The speed-ease and glint-sweep sub-frames are dropped entirely at 1fps — skipping them costs nothing because the ticker already proves liveness.
- **STOPPING (§8.5)** — hold each of the 3 lock-steps for a minimum of 1 full second even though the 8-12fps renderer holds them for ~0.3s. The near-miss overshoot frame gets the same treatment: **hold it a full 1.0s minimum** rather than its native ~80ms, so a 1fps viewer actually gets to see the illusory triple before the snap — this is the one frame in the whole spec where the 1fps version is *more* visible than the 8-12fps original, deliberately, because it's the single highest-tension frame in the near-miss story.
- **REVEAL (§8.6)** — extend the ~300ms hold to ≥1.0s so the completed combo is guaranteed at least one visible paint before the outcome animation starts.
- **OUTCOME ANIMATIONS (§8.7-8.14)** — pick keyframes, don't tween. Paint the "flash"/marquee-change frame on tick 1, then jump the payout counter straight to its final value (an intermediate tick-up number that only ever paints once looks like a bug, not an animation), then hold the settled frame for any remaining ticks. Coin-rain / sunburst / brake-jitter decoration is dropped — the marquee text and the final number carry 100% of the information.
- **LOSE (§8.12)** — the 3-frame sequence compresses to two ticks: dim+wistful-mark on tick 1, relit-normal on tick 2.
- **ABORTED / ERROR (§8.13-8.14)** — each collapses to its 2 frames, one per tick (brake→settled). Never collapse to a single frame: a 1fps viewer must see the reel bank actually change state (brake→placeholder), not just appear with the final marquee already showing, or the "something happened mid-spin" read is lost.

General clamp: **any hold or transition spec'd under ~1.0s must be extended to a 1.0s minimum specifically in the 1fps renderer** (never in the 8-12fps one). That single rule keeps every phase legible at 1fps without a second design pass per phase.
""")

